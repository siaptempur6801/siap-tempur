-- Siap Tempur Schema V2 canonical runtime schema extractor
-- READ ONLY against canonical staging: lpgrivowdcepcxradavu
--
-- This script only SELECTs DDL text. It does NOT execute the generated DDL.
-- Capture each result set into source-controlled bootstrap fragments, review it,
-- then prove the assembled bootstrap in an isolated/local rehearsal.
-- NEVER pipe this output directly into production.
--
-- Runtime target intentionally EXCLUDES CPNS migration-only staging objects:
--   app_private.cpns_legacy_import_stage
--   app_private.cpns_legacy_mapping_reviews
--   app_private.cpns_skd_p1_import_stage
--   app_private.cpns_legacy_import_ready
--   app_private.cpns_legacy_mapping_review_summary
--   app_private.validate_cpns_legacy_mapping_review()
--   public.get_cpns_legacy_import_summary()
--   public.import_reviewed_cpns_legacy_batch(...)
--   public.import_reviewed_cpns_legacy_question(...)
--   public.stage_cpns_legacy_question(...)
--   public.upsert_cpns_legacy_mapping_review(...)
-- 00) Required private runtime schema.
SELECT
  'CREATE SCHEMA IF NOT EXISTS app_private;' AS ddl;

-- 01) Sequences used by canonical public tables.
SELECT
  'CREATE SEQUENCE public.' || quote_ident(sequencename) || ' AS ' || data_type || ' INCREMENT BY ' || increment_by || ' MINVALUE ' || min_value || ' MAXVALUE ' || max_value || ' START WITH ' || start_value || CASE WHEN CYCLE THEN
    ' CYCLE'
  ELSE
    ' NO CYCLE'
  END || ';' AS ddl
FROM
  pg_sequences
WHERE
  schemaname = 'public'
ORDER BY
  sequencename;

-- 02) Public canonical tables, columns/defaults only.
-- Constraints are emitted separately after all tables exist.
WITH cols AS (
  SELECT
    c.relname,
    a.attnum,
    a.attname,
    pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,
    a.attnotnull,
    a.attidentity::text AS identity_kind,
    a.attgenerated::text AS generated_kind,
    pg_get_expr(ad.adbin, ad.adrelid) AS expr
  FROM
    pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.oid
      AND a.attnum > 0
      AND NOT a.attisdropped
    LEFT JOIN pg_attrdef ad ON ad.adrelid = c.oid
      AND ad.adnum = a.attnum
  WHERE
    n.nspname = 'public'
    AND c.relkind IN ('r', 'p'))
SELECT
  'CREATE TABLE public.' || quote_ident(relname) || E' (\n  ' || string_agg(quote_ident(attname) || ' ' || data_type || CASE WHEN generated_kind = 's' THEN
      ' GENERATED ALWAYS AS (' || expr || ') STORED'
    WHEN identity_kind = 'a' THEN
      ' GENERATED ALWAYS AS IDENTITY'
    WHEN identity_kind = 'd' THEN
      ' GENERATED BY DEFAULT AS IDENTITY'
    WHEN expr IS NOT NULL THEN
      ' DEFAULT ' || expr
    ELSE
      ''
    END || CASE WHEN attnotnull THEN
      ' NOT NULL'
    ELSE
      ''
    END, E',\n  ' ORDER BY attnum) || E'\n);' AS ddl
FROM
  cols
GROUP BY
  relname
ORDER BY
  relname;

-- 03) Sequence ownership.
SELECT
  'ALTER SEQUENCE ' || quote_ident(ns.nspname) || '.' || quote_ident(seq.relname) || ' OWNED BY ' || quote_ident(nt.nspname) || '.' || quote_ident(tab.relname) || '.' || quote_ident(att.attname) || ';' AS ddl
FROM
  pg_class seq
  JOIN pg_namespace ns ON ns.oid = seq.relnamespace
  JOIN pg_depend dep ON dep.objid = seq.oid
    AND dep.classid = 'pg_class'::regclass
    AND dep.deptype = 'a'
  JOIN pg_class tab ON tab.oid = dep.refobjid
  JOIN pg_namespace nt ON nt.oid = tab.relnamespace
  JOIN pg_attribute att ON att.attrelid = tab.oid
    AND att.attnum = dep.refobjsubid
WHERE
  seq.relkind = 'S'
  AND ns.nspname = 'public'
  AND nt.nspname = 'public'
ORDER BY
  seq.relname;

-- 04) PK / UNIQUE / CHECK / FK constraints after every table exists.
SELECT
  'ALTER TABLE ' || quote_ident(n.nspname) || '.' || quote_ident(c.relname) || ' ADD CONSTRAINT ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid, TRUE) || ';' AS ddl
FROM
  pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE
  n.nspname = 'public'
ORDER BY
  CASE con.contype
  WHEN 'p' THEN
    1
  WHEN 'u' THEN
    2
  WHEN 'c' THEN
    3
  WHEN 'f' THEN
    4
  ELSE
    5
  END,
  c.relname,
  con.conname;

-- 05) Standalone indexes only. Constraint-owned indexes are created by section 04.
SELECT
  pg_get_indexdef(i.oid) || ';' AS ddl
FROM
  pg_index x
  JOIN pg_class tab ON tab.oid = x.indrelid
  JOIN pg_namespace n ON n.oid = tab.relnamespace
  JOIN pg_class i ON i.oid = x.indexrelid
  LEFT JOIN pg_constraint con ON con.conindid = i.oid
WHERE
  n.nspname = 'public'
  AND con.oid IS NULL
ORDER BY
  tab.relname,
  i.relname;

-- 06) Runtime functions/procedures from public + app_private.
-- CPNS migration-only helpers are deliberately excluded.
SELECT
  pg_get_functiondef(p.oid) || E'\n' AS ddl
FROM
  pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE
  n.nspname IN ('public', 'app_private')
  AND p.prokind IN ('f', 'p')
  AND NOT (n.nspname = 'app_private'
    AND p.proname = 'validate_cpns_legacy_mapping_review')
  AND NOT (n.nspname = 'public'
    AND p.proname IN ('get_cpns_legacy_import_summary', 'import_reviewed_cpns_legacy_batch', 'import_reviewed_cpns_legacy_question', 'stage_cpns_legacy_question', 'upsert_cpns_legacy_mapping_review'))
ORDER BY
  n.nspname,
  p.proname,
  pg_get_function_identity_arguments(p.oid);

-- 07) Runtime public views/materialized views, if any.
SELECT
  CASE c.relkind
  WHEN 'm' THEN
    'CREATE MATERIALIZED VIEW '
  ELSE
    'CREATE VIEW '
  END || quote_ident(n.nspname) || '.' || quote_ident(c.relname) || ' AS ' || pg_get_viewdef(c.oid, TRUE) || ';' AS ddl
FROM
  pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE
  n.nspname = 'public'
  AND c.relkind IN ('v', 'm')
ORDER BY
  c.relname;

-- 08) RLS. Canonical staging currently has RLS enabled on all public runtime tables.
SELECT
  'ALTER TABLE public.' || quote_ident(c.relname) || ' ENABLE ROW LEVEL SECURITY;' AS ddl
FROM
  pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE
  n.nspname = 'public'
  AND c.relkind IN ('r', 'p')
  AND c.relrowsecurity
ORDER BY
  c.relname;

-- 09) RLS policies.
SELECT
  'CREATE POLICY ' || quote_ident(policyname) || ' ON ' || quote_ident(schemaname) || '.' || quote_ident(tablename) || CASE WHEN permissive = 'RESTRICTIVE' THEN
    ' AS RESTRICTIVE'
  ELSE
    ' AS PERMISSIVE'
  END || ' FOR ' || cmd || ' TO ' || (
    SELECT
      string_agg(quote_ident(r), ', ' ORDER BY r)
    FROM
      unnest(roles) r) || CASE WHEN qual IS NOT NULL THEN
    ' USING (' || qual || ')'
  ELSE
    ''
  END || CASE WHEN with_check IS NOT NULL THEN
    ' WITH CHECK (' || with_check || ')'
  ELSE
    ''
  END || ';' AS ddl
FROM
  pg_policies
WHERE
  schemaname = 'public'
ORDER BY
  tablename,
  policyname;

-- 10) Runtime public triggers. The auth.users trigger already exists on legacy production
-- with the same trigger definition, so only its handler function must be reconciled.
SELECT
  pg_get_triggerdef(t.oid, TRUE) || ';' AS ddl
FROM
  pg_trigger t
  JOIN pg_class c ON c.oid = t.tgrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE
  NOT t.tgisinternal
  AND n.nspname = 'public'
ORDER BY
  c.relname,
  t.tgname;

-- 11) Schema ACL source state.
SELECT
  n.nspname,
  coalesce(grantee.rolname, 'PUBLIC') AS grantee,
  x.privilege_type,
  x.is_grantable
FROM
  pg_namespace n
  CROSS JOIN LATERAL aclexplode(coalesce(n.nspacl, acldefault('n', n.nspowner))) x
  LEFT JOIN pg_roles grantee ON grantee.oid = x.grantee
WHERE
  n.nspname IN ('public', 'app_private')
ORDER BY
  n.nspname,
  grantee,
  privilege_type;

-- 12) Runtime table/sequence grants for non-owner application roles.
-- Final bootstrap should REVOKE client-role defaults before applying these grants.
SELECT
  n.nspname AS schema_name,
  c.relname AS object_name,
  c.relkind,
  coalesce(grantee.rolname, 'PUBLIC') AS grantee,
  x.privilege_type,
  x.is_grantable
FROM
  pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  CROSS JOIN LATERAL aclexplode(coalesce(c.relacl, acldefault(
        CASE WHEN c.relkind = 'S' THEN
          'S'::"char"
        ELSE
          'r'::"char"
        END, c.relowner))) x
  LEFT JOIN pg_roles grantee ON grantee.oid = x.grantee
WHERE
  n.nspname = 'public'
  AND c.relkind IN ('r', 'p', 'v', 'm', 'S')
  AND coalesce(grantee.rolname, 'PUBLIC') IN ('PUBLIC', 'anon', 'authenticated', 'service_role')
ORDER BY
  n.nspname,
  c.relname,
  grantee,
  privilege_type;

-- 13) Runtime function grants for non-owner application roles.
SELECT
  n.nspname AS schema_name,
  p.proname,
  pg_get_function_identity_arguments(p.oid) AS args,
  coalesce(grantee.rolname, 'PUBLIC') AS grantee,
  x.privilege_type,
  x.is_grantable
FROM
  pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  CROSS JOIN LATERAL aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
  LEFT JOIN pg_roles grantee ON grantee.oid = x.grantee
WHERE
  n.nspname IN ('public', 'app_private')
  AND p.prokind IN ('f', 'p')
  AND NOT (n.nspname = 'app_private'
    AND p.proname = 'validate_cpns_legacy_mapping_review')
  AND NOT (n.nspname = 'public'
    AND p.proname IN ('get_cpns_legacy_import_summary', 'import_reviewed_cpns_legacy_batch', 'import_reviewed_cpns_legacy_question', 'stage_cpns_legacy_question', 'upsert_cpns_legacy_mapping_review'))
  AND coalesce(grantee.rolname, 'PUBLIC') IN ('PUBLIC', 'anon', 'authenticated', 'service_role')
ORDER BY
  n.nspname,
  p.proname,
  args,
  grantee,
  privilege_type;
