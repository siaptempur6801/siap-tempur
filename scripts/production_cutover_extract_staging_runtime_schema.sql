-- Siap Tempur Schema V2 canonical runtime schema extractor
-- READ ONLY against canonical staging: lpgrivowdcepcxradavu
--
-- This script only SELECTs DDL text. It does NOT execute the generated DDL.
-- Capture each result set into source-controlled bootstrap fragments, review it,
-- then prove the assembled bootstrap in an isolated/local rehearsal.
-- NEVER pipe this output directly into production.
--
-- Runtime target intentionally EXCLUDES CPNS migration-only staging objects:
--   app_private.cpns_legacy_import_stage
--   app_private.cpns_legacy_mapping_reviews
--   app_private.cpns_skd_p1_import_stage
--   app_private.cpns_legacy_import_ready
--   app_private.cpns_legacy_mapping_review_summary
--   app_private.validate_cpns_legacy_mapping_review()
--   public.get_cpns_legacy_import_summary()
--   public.import_reviewed_cpns_legacy_batch(...)
--   public.import_reviewed_cpns_legacy_question(...)
--   public.stage_cpns_legacy_question(...)
--   public.upsert_cpns_legacy_mapping_review(...)

-- 00) Required private runtime schema.
select 'CREATE SCHEMA IF NOT EXISTS app_private;' as ddl;

-- 01) Sequences used by canonical public tables.
select
  'CREATE SEQUENCE public.'||quote_ident(sequencename)||
  ' AS '||data_type||
  ' INCREMENT BY '||increment_by||
  ' MINVALUE '||min_value||
  ' MAXVALUE '||max_value||
  ' START WITH '||start_value||
  case when cycle then ' CYCLE' else ' NO CYCLE' end||';' as ddl
from pg_sequences
where schemaname='public'
order by sequencename;

-- 02) Public canonical tables, columns/defaults only.
-- Constraints are emitted separately after all tables exist.
with cols as (
 select c.relname,a.attnum,a.attname,
        pg_catalog.format_type(a.atttypid,a.atttypmod) as data_type,
        a.attnotnull,a.attidentity::text as identity_kind,
        a.attgenerated::text as generated_kind,
        pg_get_expr(ad.adbin,ad.adrelid) as expr
 from pg_class c
 join pg_namespace n on n.oid=c.relnamespace
 join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
 left join pg_attrdef ad on ad.adrelid=c.oid and ad.adnum=a.attnum
 where n.nspname='public' and c.relkind in ('r','p')
)
select 'CREATE TABLE public.'||quote_ident(relname)||E' (\n  '||
       string_agg(
         quote_ident(attname)||' '||data_type||
         case
           when generated_kind='s' then ' GENERATED ALWAYS AS ('||expr||') STORED'
           when identity_kind='a' then ' GENERATED ALWAYS AS IDENTITY'
           when identity_kind='d' then ' GENERATED BY DEFAULT AS IDENTITY'
           when expr is not null then ' DEFAULT '||expr
           else ''
         end||case when attnotnull then ' NOT NULL' else '' end,
         E',\n  ' order by attnum
       )||E'\n);' as ddl
from cols
group by relname
order by relname;

-- 03) Sequence ownership.
select 'ALTER SEQUENCE '||quote_ident(ns.nspname)||'.'||quote_ident(seq.relname)||
       ' OWNED BY '||quote_ident(nt.nspname)||'.'||quote_ident(tab.relname)||'.'||quote_ident(att.attname)||';' as ddl
from pg_class seq
join pg_namespace ns on ns.oid=seq.relnamespace
join pg_depend dep on dep.objid=seq.oid and dep.classid='pg_class'::regclass and dep.deptype='a'
join pg_class tab on tab.oid=dep.refobjid
join pg_namespace nt on nt.oid=tab.relnamespace
join pg_attribute att on att.attrelid=tab.oid and att.attnum=dep.refobjsubid
where seq.relkind='S' and ns.nspname='public' and nt.nspname='public'
order by seq.relname;

-- 04) PK / UNIQUE / CHECK / FK constraints after every table exists.
select 'ALTER TABLE '||quote_ident(n.nspname)||'.'||quote_ident(c.relname)||
       ' ADD CONSTRAINT '||quote_ident(con.conname)||' '||pg_get_constraintdef(con.oid,true)||';' as ddl
from pg_constraint con
join pg_class c on c.oid=con.conrelid
join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public'
order by case con.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'f' then 4 else 5 end,
         c.relname,con.conname;

-- 05) Standalone indexes only. Constraint-owned indexes are created by section 04.
select pg_get_indexdef(i.oid)||';' as ddl
from pg_index x
join pg_class tab on tab.oid=x.indrelid
join pg_namespace n on n.oid=tab.relnamespace
join pg_class i on i.oid=x.indexrelid
left join pg_constraint con on con.conindid=i.oid
where n.nspname='public' and con.oid is null
order by tab.relname,i.relname;

-- 06) Runtime functions/procedures from public + app_private.
-- CPNS migration-only helpers are deliberately excluded.
select pg_get_functiondef(p.oid)||E'\n' as ddl
from pg_proc p
join pg_namespace n on n.oid=p.pronamespace
where n.nspname in ('public','app_private')
  and p.prokind in ('f','p')
  and not (n.nspname='app_private' and p.proname='validate_cpns_legacy_mapping_review')
  and not (n.nspname='public' and p.proname in (
    'get_cpns_legacy_import_summary',
    'import_reviewed_cpns_legacy_batch',
    'import_reviewed_cpns_legacy_question',
    'stage_cpns_legacy_question',
    'upsert_cpns_legacy_mapping_review'
  ))
order by n.nspname,p.proname,pg_get_function_identity_arguments(p.oid);

-- 07) Runtime public views/materialized views, if any.
select case c.relkind when 'm' then 'CREATE MATERIALIZED VIEW ' else 'CREATE VIEW ' end||
       quote_ident(n.nspname)||'.'||quote_ident(c.relname)||' AS '||pg_get_viewdef(c.oid,true)||';' as ddl
from pg_class c
join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relkind in ('v','m')
order by c.relname;

-- 08) RLS. Canonical staging currently has RLS enabled on all public runtime tables.
select 'ALTER TABLE public.'||quote_ident(c.relname)||' ENABLE ROW LEVEL SECURITY;' as ddl
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relkind in ('r','p') and c.relrowsecurity
order by c.relname;

-- 09) RLS policies.
select 'CREATE POLICY '||quote_ident(policyname)||' ON '||quote_ident(schemaname)||'.'||quote_ident(tablename)||
       case when permissive='RESTRICTIVE' then ' AS RESTRICTIVE' else ' AS PERMISSIVE' end||
       ' FOR '||cmd||
       ' TO '||(select string_agg(quote_ident(r),', ' order by r) from unnest(roles) r)||
       case when qual is not null then ' USING ('||qual||')' else '' end||
       case when with_check is not null then ' WITH CHECK ('||with_check||')' else '' end||';' as ddl
from pg_policies
where schemaname='public'
order by tablename,policyname;

-- 10) Runtime public triggers. The auth.users trigger already exists on legacy production
-- with the same trigger definition, so only its handler function must be reconciled.
select pg_get_triggerdef(t.oid,true)||';' as ddl
from pg_trigger t
join pg_class c on c.oid=t.tgrelid
join pg_namespace n on n.oid=c.relnamespace
where not t.tgisinternal and n.nspname='public'
order by c.relname,t.tgname;

-- 11) Schema ACL source state.
select n.nspname,
       coalesce(grantee.rolname,'PUBLIC') as grantee,
       x.privilege_type,x.is_grantable
from pg_namespace n
cross join lateral aclexplode(coalesce(n.nspacl,acldefault('n',n.nspowner))) x
left join pg_roles grantee on grantee.oid=x.grantee
where n.nspname in ('public','app_private')
order by n.nspname,grantee,privilege_type;

-- 12) Runtime table/sequence grants for non-owner application roles.
-- Final bootstrap should REVOKE client-role defaults before applying these grants.
select n.nspname as schema_name,c.relname as object_name,c.relkind,
       coalesce(grantee.rolname,'PUBLIC') as grantee,
       x.privilege_type,x.is_grantable
from pg_class c
join pg_namespace n on n.oid=c.relnamespace
cross join lateral aclexplode(coalesce(c.relacl,acldefault(case when c.relkind='S' then 'S'::"char" else 'r'::"char" end,c.relowner))) x
left join pg_roles grantee on grantee.oid=x.grantee
where n.nspname='public'
  and c.relkind in ('r','p','v','m','S')
  and coalesce(grantee.rolname,'PUBLIC') in ('PUBLIC','anon','authenticated','service_role')
order by n.nspname,c.relname,grantee,privilege_type;

-- 13) Runtime function grants for non-owner application roles.
select n.nspname as schema_name,p.proname,
       pg_get_function_identity_arguments(p.oid) as args,
       coalesce(grantee.rolname,'PUBLIC') as grantee,
       x.privilege_type,x.is_grantable
from pg_proc p
join pg_namespace n on n.oid=p.pronamespace
cross join lateral aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) x
left join pg_roles grantee on grantee.oid=x.grantee
where n.nspname in ('public','app_private')
  and p.prokind in ('f','p')
  and not (n.nspname='app_private' and p.proname='validate_cpns_legacy_mapping_review')
  and not (n.nspname='public' and p.proname in (
    'get_cpns_legacy_import_summary',
    'import_reviewed_cpns_legacy_batch',
    'import_reviewed_cpns_legacy_question',
    'stage_cpns_legacy_question',
    'upsert_cpns_legacy_mapping_review'
  ))
  and coalesce(grantee.rolname,'PUBLIC') in ('PUBLIC','anon','authenticated','service_role')
order by n.nspname,p.proname,args,grantee,privilege_type;
